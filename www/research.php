<b>Topics of Past Research</b>
<br>
<br>

<font size=2 face="Arial" color="#000000" style="font-size:10pt">
<P align="justify">
A deep open problem in representation theory is the problem of 
classification of all simple modules \(M\) over simple Lie
algebras, satisfying the condition that \(M\) decomposes as a direct
sum of finite-dimensional isotypic components over a suitable
subalgebra. In the late 1990's my collaborators and I gave these
representations the name generalized Harish Chandra modules and
initiated a program to study them. A success of our team has been the construction of large classes
of new generalized Harish Chandra modules, as well as the
description of arbitrary reductive subalgebras over which
generalized Harish Chandra modules can have finite-dimensional
isotypic components. Some publications on this subject are 30, 36, 41, 42, 44, 49, 51, 57, 60. 
In 2010
my PhD student Todor Milev defended his thesis, "On root Fernando-Kac subalgebras of finite type", in which he characterized all Fernando-Kac subalgebras
of finite type which contain a Cartan subalgebra (i.e. they are root Fernando-Kac subalgebras) of an arbitrary simple Lie algebra not isomorphic to \(E_8\). In 2011 my PhD student Alexey Petukhov defended his PhD thesis "A geometric approach to the study of \((\mathfrak{g},\mathfrak{k})\)-modules of finite type" in which
he establishes important new results on \((\mathfrak{g},\mathfrak{k})\)-modules, and in particular on bounded \((\mathfrak{g},\mathfrak{k})\)-modules. A substantial paper in this direction is the joint paper 70, in which we establish an equivalence between a category of generalized Harish-Chandra modules and a "semithick" category \(\mathcal{O}\). In the latest paper 79 we prove a general result of existence of generalized Harish-Chandra modules.
</P>
<P align="justify">
Another program, in which I have been actively working is the structure
theory of locally finite Lie algebras. For the three classical algebras \(\mathfrak{sl}_\infty\), \(\mathfrak{so}_\infty\), \(\mathfrak{sp}_\infty\) my collaborators and I have developed
 a structure theory
which is almost as detailed as the classical structure theory
of finite-dimensional Lie algebras.
In particular we have given complete description of Cartan, Borel and parabolic
subalgebras, and we have studied weight modules and tensor modules.
These results are based on innovative infinite-dimensional techniques such
as generalized flags and the corresponding homogeneous ind-spaces. 
My relevant algebraic publications on this subject are 33, 35, 40, 43, 45, 46, 47, 50, 54. 
</P>

<P align="justify"> 
The papers 31, 39, 53, and 73 are devoted to a geometric approach and 
study infinite-dimensional flag varieties and an
infinite-dimensional version of the Borel-Weil-Bott theorem.  The cluster of papers 66, 69, 74, and 84 studies
 orbit structures on ind-varieties of generalized flags, and in particular establishes an analogue of Matsuki duality 
 for ind-varieties of generalized flags.  The paper 72 is a survey of results on ind-varieties of generalized flags. 
 In 82 we initiate  the study of automorphism groups of ind-varieties of generalized flags. 
 In the paper 83 we provide a purely algebraic-geometric construction of an arbitrary ind-varietiy of generalized flags.
</P>



<P align="justify">
The study of the geometry of ind-varieties of generalized flags is closely related to a program in infinite-dimensional algebraic geometry which I am persuing. More specifically, I am studying vector bundles of finite rank on
flag ind-spaces, and I conjecture that under some very mild assumptions, any such bundle is equivariant. 
In 2010 A. Tikhomirov and I proved this conjecture for the case of ind-Grassmannians.
The relevant publications are 34, 48, 52. In addition, A. Tikhomirov and I have made advances in two directions: we have classified all linear ind-grassmanianians, see 59, and have proved a very general version of the Barth-Van der Ven-Tyurin-Sato Theorem, see 62.
</p>

<P align="justify"> 
A further direction of study is the structure of diagonal Lie algebras (these locally finite Lie algebras have been introduced by A. Baranov
 and his collaborators). In 2010 my PhD student Siarhei Markouski defended his thesis, "On homomorphisms of diagonal Lie algebras", in which he described
when a locally simple diagonal Lie algebra admits a non-zero homomoprhism into another locally simple diagonal Lie algebra.  
</P>

<P align="justify">
Vera Serganova and I are actively studying various subcategories of the category of integrable modules for a finitary Lie algebra.
In particular, together with Elizabeth Dan-Cohen, we have constructed and studied the category of tensor modules. One of our main results is that
Koszul duality holds for this category. The relevant publications are 54, 56, and 61. Furthermore, Alexey Petukhov and I have made significant progress in understanding the ideals in the enveloping algebra of a locally finite Lie algebra, and in particular have proved the conjecture of Baranov, see 58. In the paper 64 we study annihilators of highest weight modules and prove an analog of the famous Duflo Theorem. The paper 67 is a survey of results until 2016.  In the paper 71 Petukhov and I gave a classification of primitive ideals of \(U(\mathfrak{sl}_\infty)\). The algorithm computing the primitive ideal of a given simple highest weight module is presented in paper 76. In 2013 my PhD student Elitza Hristova defended her PhD thesis "Branching laws for tensor modules over classical locally finite Lie algebras". In addition, Frenkel, Serganova and I have been able to use the results and methods of paper 56 in order to categorify the boson-fermion correspondence, see 63. Recently, in the paper 77 we found a spectacular category of integrable \(\mathfrak{sl}_\infty\)-modules whose categorification is category \(\mathcal{O}\) for the Lie superagebra \(GL(m|n)\). This work builds on previous work of J. Brundan.
</P>
<P align="justify"> 
Mackey Lie algebras are certain matrix Lie algebras whose elements are truly infinite matrices. The study of their representations was initiated in the paper 61. Recently, A. Chirvasitu and I have studied more challenging categories  of representations of Mackey Lie algebras, see 68 and 75.
</P>

<P align="justify">
My collaborators and I have started a systematic study of categories \(\mathcal{O}\) for the three classical Lie algebras \(\mathfrak{sl}_\infty\), \(\mathfrak{so}_\infty\), \(\mathfrak{sp}_\infty\).  The first paper in this direction is the dissertation of my PhD student Thanasin Nampaisarn (in 2017) in which he constructs an analogues of category \(\mathcal{O}\) for Dynkin Borel subalgebras. The paper 78 is a deeper study of the properties  of the categories introduced by Nampaisarn.
</P>

<P align="justify"> 
In the paper 80, D. Grantcharov and I have classified the simple bounded weight modules of \(\mathfrak{sl}_\infty\), \(\mathfrak{so}_\infty\), \(\mathfrak{sp}_\infty\).
</P>

<P align="justify">
For papers with numbers 81 and larger, please see the introductions to those papers for brief summaries of results.
</P>

