<h1>Abstracts</h1>

<h2>Corrado De Concini - Projective varieties arising from pre homogeneous vector spaces</h2>

<p>Following some old work joint with Lusztig and Procesi, we introduce some smooth sub varieties of flag varieties and try to say something about their geometry.</p>

<h2>Alberto De Sole - Integrability of classical affine W-algebras</h2>

<p>All classical affine W-algebras W(g,f), where g is a simple Lie algebra and f is its non-zero nilpotent element, admit an integrable hierarchy of bi-Hamiltonian PDEs, except possibly for one nilpotent conjugacy class in G2, one in F4, and five in E8.</p>


<h2>Dimitar Grantcharov -  Bounded weight modules of Lie algebras and superalgebras at infinity.</h2>

<p>In this talk we will discuss bounded weight modules, i.e., modules that decompose as direct sums of weight spaces and whose sets of weight multiplicities are uniformly bounded. Our main focus will be on direct limits of classical Lie algebras and superalgebras. In particular, we will present the classification of the simple bounded weight modules over sl(infty), o(infty), sp (infty), as well as over their super-analogs. A key role in the study plays the theory of weight modules over Weyl and Clifford superalgebras of infinitely many variables. The talk is based on joint works with I. Penkov and V. Serganova.</p>


<h2>Michela Varagnolo - Critical convolution algebras and quantum loop groups</h2>

<p>I will introduce  a new family of algebras attached to quivers with potentials, using critical K-theory. They generalize the convolution algebras attached to quivers defined by Nakajima and are in some sense doubles of K-theoretical Hall algebras recently introduced by  Padurariu.</p>

<p>As an application I will give (for Dynkin types) a geometrical construction of  Kirillov-Reshetikhin and prefundamental representations of the quantum loop group (or a shifted version). This is a joint work with Eric Vasserot.</p>
